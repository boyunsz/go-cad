// seqend 输出 POLYLINE 的 SEQEND（合成句柄；模型空间记录归属）。
func (x *DxfWriter) seqend(owner uint64, pspace bool) {
	h := uint64(0)
	for _, e := range x.Doc.Blocks[owner] {
		if b := entity.EntityBase(e); b != nil && b.TypeName == "SEQEND" {
			h = b.Handle
			break
		}
	}
	if h == 0 {
		h = x.alloc.take()
	}
	x.str(0, "SEQEND")
	x.hex(5, h)
	x.hex(330, owner)
	x.str(100, "AcDbEntity")
	x.str(8, "0")
}

// HATCH。

// writeHatch 输出填充：边界路径统一按“多段线路径”形式（渲染同源的细分
// 点列）写出；图案定义按解析结果输出（solidFill 时读者无需图案段）。
// 组码顺序对齐 dwg.spec 的 DXF 分支：92(bit1=polyline)/72/73/93/10+20/97，
// 尾随 75/76 与图案段 52/41/77/78/53/43/44/45/46/79/49。
func (x *DxfWriter) writeHatch(e *entity.EntHatch, pspace bool) {
	x.entityHead(&e.BaseEntity, "HATCH", pspace)
	x.subclass("AcDbHatch")
	x.flt(10, 0)
	x.flt(20, 0)
	x.flt(30, e.Elevation)
	x.vec3(210, e.Extrusion)
	if e.SolidFill {
		x.str(2, "SOLID")
	} else {
		x.str(2, e.Name)
	}
	x.codeValue(70, BoolToInt(e.SolidFill))
	x.codeValue(71, BoolToInt(e.Associative))
	x.codeValue(91, int64(len(e.Paths)))
	for _, p := range e.Paths {
		// LibreDWG 以 bit1 判定 polyline 路径（非 DXF 文档的 bit0）；
		// 清 bit2（derived）避免读者期待随后的 47 pixel_size
		x.codeValue(92, (int64(p.Flag)|2)&^4)
		x.codeValue(72, 0) // bulges_present=0：细分点列不携带 bulge
		x.codeValue(73, BoolToInt(p.Closed))
		x.codeValue(93, int64(len(p.Points)))
		for _, v := range p.Points {
			x.pt2(10, v)
		}
		x.codeValue(97, 0) // 源边界对象数
	}
	x.codeValue(75, int64(e.Style))
	x.codeValue(76, int64(e.PatternType))
	if !e.SolidFill {
		x.flt(52, e.Angle)
		if e.ScaleSpacing != 1 {
			x.flt(41, e.ScaleSpacing)
		}
		x.codeValue(77, BoolToInt(e.DoubleFlag))
		x.codeValue(78, int64(len(e.Deflines)))
		for _, d := range e.Deflines {
			// 2BD_1 组码：y 值组码为 x 组码 +1（43/44、45/46）
			x.flt(53, d.Angle)
			x.flt(43, d.Pt0.X)
			x.flt(44, d.Pt0.Y)
			x.flt(45, d.Offset.X)
			x.flt(46, d.Offset.Y)
			x.codeValue(79, int64(len(d.Dashes)))
			for _, dash := range d.Dashes {
				x.flt(49, dash)
			}
		}
	}
	// 写入种子点及渐变填充参数。
	// 顺序为 98 → 450/451/460/461/452/462/453 → 各颜色项 → 470。
	x.codeValue(98, int64(len(e.Seeds)))
	for _, s := range e.Seeds {
		x.pt2(10, s)
	}
	if e.IsGradientFill != 0 {
		x.codeValue(450, int64(e.IsGradientFill))
		x.codeValue(451, int64(e.Reserved))
		x.radDeg(460, e.GradientAngle) // 模型侧弧度 → DXF 度
		x.flt(461, e.GradientShift)
		x.codeValue(452, int64(e.SingleColorGradient))
		x.flt(462, e.GradientTint)
		x.codeValue(453, int64(len(e.Colors)))
		for _, c := range e.Colors {
			x.flt(463, c.ShiftValue)
			x.codeValue(63, c.ColorIndex)
			// CMC rgb 的 method 高字节为 0xc2（真彩无 index 混合）时
			// out_dxf 不输出 421，其余按 63+420-62=421 输出完整 32 位
			if rgb, err := strconv.ParseUint(c.ColorRGB, 16, 32); err == nil {
				if rgb>>24 != 0xc2 {
					x.codeValue(421, int64(rgb))
				}
			}
		}
		x.str(470, e.GradientName)
	}
}

// BoolToInt 布尔 → DXF 整数（0/1）。
func BoolToInt(b bool) int64 {
	if b {
		return 1
	}
	return 0
}

// DIMENSION。

// dxfDimSubclass 标注 DXF 70 低 3 位类型 → 子类名（与 dimFlag 合成规则对应）。
func dxfDimSubclass(flag uint8) string {
	switch flag & 0x7 {
	case 1:
		return "AcDbAlignedDimension"
	case 2:
		return "AcDb2LineAngularDimension"
	case 3:
		return "AcDbDiametricDimension"
	case 4:
		return "AcDbRadialDimension"
	case 5:
		return "AcDb3PointAngularDimension"
	case 6:
		return "AcDbOrdinateDimension"
	default:
		return "AcDbRotatedDimension"
	}
}

// writeDimension 标注：公共段（AcDbDimension）+ 类型专属子类段。
// 定义点映射与 dxf_cross_test 对齐：非 ANG2LN 的 10=point10；
// ANG2LN 的 10=（point16x,p16y）、16=point10。
func (x *DxfWriter) writeDimension(e *entity.EntDimension, pspace bool) {
	flag := e.DimFlag
	if v, ok := map[string]uint8{"DIM_LINEAR": 0, "DIM_ALIGNED": 1, "DIM_ANG2LN": 2, "DIM_DIAMETER": 3, "DIM_RADIUS": 4, "DIM_ANG3PT": 5, "DIM_ORDINATE": 6}[e.TypeName]; ok {
		flag = flag&^7 | v
	}
	sub := dxfDimSubclass(flag)
	ang2ln := sub == "AcDb2LineAngularDimension"
	x.entityHead(&e.BaseEntity, "DIMENSION", pspace)
	x.subclass("AcDbDimension")
	if e.AnonymousBlock != 0 {
		x.str(2, x.blockName(e.AnonymousBlock))
	}
	if ang2ln {
		x.flt(10, e.Point16x)
		x.flt(20, e.P16y)
		x.flt(30, 0)
	} else {
		x.pt3(10, e.Point10)
	}
	x.pt3(11, e.TextMidpoint)
	x.codeValue(70, int64(flag))
	if e.UserText != "" {
		x.str(1, e.UserText)
	}
	if e.AttachmentPoint != 0 {
		x.codeValue(71, int64(e.AttachmentPoint))
	}
	if e.ActualMeasurement != 0 {
		x.flt(42, e.ActualMeasurement)
	}
	if e.InsertRotation != 0 {
		x.radDeg(54, e.InsertRotation)
	}
	if e.HorizontalDir != 0 {
		x.radDeg(51, e.HorizontalDir)
	}
	if e.TextRotation != 0 {
		x.radDeg(53, e.TextRotation)
	}
	x.pt3(13, e.Point13)
	x.pt3(14, e.Point14)

	x.subclass(sub)
	switch sub {
	case "AcDb2LineAngularDimension":
		x.pt3(15, e.Point15)
		x.pt3(16, e.Point10)
	case "AcDb3PointAngularDimension":
		x.pt3(15, e.Point15)
	case "AcDbRotatedDimension", "AcDbAlignedDimension":
		if e.DimRotation != 0 {
			x.radDeg(50, e.DimRotation)
		}
		if e.ExtLineRotation != 0 {
			x.radDeg(52, e.ExtLineRotation)
		}
	}
}

// blockHandles 收集模型、纸张及块定义的唯一句柄，按数值排序供 DXF 稳定写出。
func (x *DxfWriter) blockHandles() []uint64 {
	set := map[uint64]bool{x.alloc.msRecord: true, x.alloc.psRecord: true}
	for h, g := range x.Doc.InternalObjs {
		if g.Name == "BLOCK_HEADER" {
			set[h] = true
		}
	}
	for h := range x.Doc.Blocks {
		if x.Doc.ByHandle[h] == nil {
			set[h] = true
		}
	}
	var hs []uint64
	for h := range set {
		hs = append(hs, h)
	}
	sort.Slice(hs, func(i, j int) bool { return hs[i] < hs[j] })
	return hs
}

// blockMarkers 查找指定块的 BLOCK/ENDBLK 标记，优先使用有效的块头引用。
// 缺少标记时从写出器分配新句柄，因此会推进句柄分配状态。
func (x *DxfWriter) blockMarkers(h uint64) (uint64, uint64) {
	var start, end uint64
	for _, e := range x.Doc.ByHandle {
		b := entity.EntityBase(e)
		if b == nil || b.Owner != h {
			continue
		}
		if b.TypeName == "BLOCK" {
			start = b.Handle
		}
		if b.TypeName == "ENDBLK" {
			end = b.Handle
		}
	}
	if g := x.Doc.InternalObjs[h]; g != nil && len(g.Handles) >= 5 {
		if b := entity.EntityBase(x.Doc.ByHandle[g.Handles[1]]); b != nil && b.TypeName == "BLOCK" {
			start = b.Handle
		}
		if b := entity.EntityBase(x.Doc.ByHandle[g.Handles[4]]); b != nil && b.TypeName == "ENDBLK" {
			end = b.Handle
		}
	}
	if start == 0 {
		start = x.alloc.take()
	}
	if end == 0 {
		end = x.alloc.take()
	}
	return start, end
}
